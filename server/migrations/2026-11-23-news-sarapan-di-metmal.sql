## Detail Ekosistem Acara "Sarapan di Metmal"

Program ini menyatukan aktivitas komunitas, kuliner pagi, dan pengalaman berbelanja dalam satu area terpadu yang terdiri dari:

- **Deretan Booth UMKM Kuliner & Produk Lokal** — Area bazar pagi yang menghadirkan beragam pilihan menu sarapan, kopi, minuman segar, hingga jajanan lokal dari pelaku UMKM. Area ini menjadi titik berkumpul dan bersantai bagi pengunjung maupun anggota komunitas setelah beraktivitas.
- **Tenant Internal Metropolitan Mall Bekasi (Morning Sale Aktif)** — Didukung langsung oleh tenant internal Metropolitan Mall Bekasi, termasuk Matahari Department Store dan Super Indo, yang sudah menjalankan program Morning Sale secara aktif di pagi hari. Kehadiran promo belanja kebutuhan harian hingga fesyen keluarga ini membuat arus pengunjung Minggu pagi di sekitar mall telah terbentuk sejak sebelum jam operasional reguler dimulai.
- **Zona Aktivitas Komunitas** — Ruang terbuka yang disiapkan khusus untuk menghadirkan ragam kegiatan interaktif lintas usia, mulai dari olahraga santai, edukasi keluarga, hingga temu hobi yang menghidupkan suasana Area Parkir Timur.

## Ruang Kolaborasi Terbuka untuk Berbagai Minat

Kolaborasi ini bersifat universal dan terbuka bagi komunitas yang memiliki agenda positif serta ramah untuk seluruh kelompok usia, antara lain:

- **Olahraga & Kebugaran Santai** — Senam pagi, line dance, yoga, tai chi, lari santai, hingga komunitas sepeda (gowes).
- **Keluarga, Anak & Literasi** — Komunitas parenting, read aloud, permainan tradisional, family playdate, serta aktivitas kreativitas anak.
- **Hobi & Gaya Hidup** — Fotografi (photo walk), berkebun (urban farming), kerajinan tangan (craft), pecinta hewan, hingga otomotif/skuter klasik (Sunday Morning Ride).
- **Seni & Hiburan** — Penampilan musik akustik pagi, seni tari, maupun mini workshop kreatif.

Format kolaborasi dapat disesuaikan secara fleksibel dengan karakter masing-masing komunitas, baik berupa sesi latihan terbuka, temu rutin (kopdar), lokakarya singkat, pameran koleksi, maupun menjadikan Area Parkir Timur sebagai titik kumpul atau titik finis rute akhir pekan.

## Manfaat bagi Mitra Komunitas

Dengan bergabung dalam program Sarapan di Metmal, komunitas akan mendapatkan dukungan ekosistem acara yang siap pakai:

- **Arus Pengunjung Pagi yang Sudah Terbentuk** — Komunitas berkesempatan menjangkau langsung pengunjung keluarga dan peserta Morning Sale Matahari serta Super Indo yang telah rutin hadir di Minggu pagi, sekaligus membuka peluang perekrutan anggota baru.
- **Lokasi Strategis & Mudah Diakses** — Akses penggunaan ruang terbuka di Area Parkir Timur yang luas dan terhubung langsung dengan area masuk Metropolitan Mall Bekasi.
- **Publikasi di Kanal Resmi** — Promosi jadwal kegiatan serta dokumentasi acara melalui kanal resmi Metropolitan Mall Bekasi dan Metmal Community Space.
- **Dukungan Fasilitas Dasar** — Penyediaan zona aktivitas, akses kelistrikan, serta koordinasi teknis lapangan sesuai kesepakatan bersama tim penyelenggara.
- **Pengalaman Akhir Pekan Terpadu** — Anggota komunitas dapat langsung menikmati beragam kuliner sarapan di booth UMKM serta memanfaatkan promo Morning Sale dari tenant internal di lokasi yang sama setelah sesi kegiatan selesai.

## Informasi Pelaksanaan

- **Hari / Tanggal:** Setiap hari Minggu
- **Waktu:** 06.30 - 10.00 WIB (slot durasi aktivitas komunitas dapat disesuaikan)
- **Lokasi:** Area Parkir Timur, Metropolitan Mall Bekasi
- **Sifat Acara:** Terbuka untuk umum (semua usia)

## Prosedur Pengajuan Kolaborasi

Komunitas yang berminat untuk berpartisipasi dalam program Sarapan di Metmal dapat mengajukan pendaftaran secara daring dengan langkah berikut:

1. Kunjungi halaman pendaftaran resmi di [metmalcommunityspace.web.id/daftar](https://metmalcommunityspace.web.id/daftar) dan pilih kategori **Komunitas** (atau kategori organisasi lain yang sesuai).
2. Lengkapi data wajib bertanda bintang (*), meliputi **Nama komunitas**, **Tipe komunitas**, **Nama PIC**, dan **Nomor WhatsApp aktif**, serta tambahkan estimasi Jumlah anggota dan akun media sosial komunitas.
3. Pilih hari Minggu yang diminati pada kolom **Preferensi tanggal event**.
4. Pada kolom **Deskripsi / proposal event**, awali dengan menulis **"Kolaborasi Sarapan di Metmal"** diikuti gambaran singkat konsep kegiatan yang diusulkan serta kebutuhan teknis dasar (jika ada).
5. Unggah proposal atau profil komunitas pada kolom **Lampiran proposal / company profile** (opsional) dalam format PDF atau Word (maksimal 20MB) apabila tersedia, lalu klik **Kirim pendaftaran**.

